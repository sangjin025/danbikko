import { test, expect } from "@playwright/test";
for (const width of [390,1440]) test('stage6 hierarchy, tray clearance and sticky comparison '+width, async ({page}) => {
  await page.setViewportSize({width,height:width===390?844:900});
  await page.goto('/products');
  const card=page.locator('.product-card').first();
  expect(await card.locator('h3').evaluate(el=>el.getBoundingClientRect().bottom)).toBeLessThan(width===390?844:900);
  expect(await card.locator('.card-evaluation').evaluate(el=>Array.from(el.children).map(e=>e.className))).toEqual(['card-grade','card-rank','card-score']);
  await page.getByRole('tab',{name:'종합',exact:true}).focus();
  await page.keyboard.press(width===390?'ArrowDown':'End');
  await expect(page.getByRole('tab',{name:width===390?'감미료·첨가물 중심':'다이어트',exact:true})).toHaveAttribute('aria-selected','true');
  for(let i=0;i<4;i++) await page.getByRole('checkbox').nth(i).check();
  const tray=page.getByRole('complementary',{name:'선택한 제품'});
  await expect(tray).toBeVisible();
  expect(await page.evaluate(()=>parseFloat(getComputedStyle(document.body).paddingBottom)>=document.querySelector('.compare-tray')!.getBoundingClientRect().height)).toBe(true);
  const last=page.getByRole('checkbox').last();
  await last.evaluate(el=>el.scrollIntoView({block:'end',behavior:'instant'}));
  expect((await last.boundingBox())!.y+(await last.boundingBox())!.height).toBeLessThan((await tray.boundingBox())!.y);
  await page.screenshot({path:'artifacts/stage6-selection-'+width+'.png'});
  await page.getByRole('link',{name:'비교하기',exact:true}).click();
  await expect(tray).toHaveCount(0);
  const table=page.locator('.comparison-scroll');
  await table.evaluate(el=>{el.scrollTop=400;el.scrollLeft=180;});
  const header=page.locator('thead th').nth(1);
  expect(Math.abs((await header.boundingBox())!.y-(await table.boundingBox())!.y)).toBeLessThan(3);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:'artifacts/stage6-compare-scrolled-'+width+'.png'});
  await page.goto('/products/v08-07');
  const reasons=page.locator('.evaluation-reasons').first();
  await expect(reasons).not.toHaveAttribute('open','');
  await reasons.locator('summary').click();
  await expect(reasons).toHaveAttribute('open','');
  await expect(reasons.locator('li').first()).toBeVisible();
});
